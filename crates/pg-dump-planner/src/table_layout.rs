use std::ffi::{CStr, c_char, c_int, c_void};

use super::selection::Archive;

/// A source table whose columns pg_dump inspected. Text uses the source client encoding.
#[derive(Clone, PartialEq, Eq, prost::Message)]
pub struct SourceTableLayout {
    #[prost(uint32, tag = "1")]
    pub relation_oid: u32,
    #[prost(bytes = "vec", tag = "2")]
    pub schema: Vec<u8>,
    #[prost(bytes = "vec", tag = "3")]
    pub name: Vec<u8>,
    /// The PostgreSQL relkind byte ('r' for ordinary tables, 'p' for partitioned tables).
    #[prost(uint32, tag = "4")]
    pub relation_kind: u32,
    #[prost(message, repeated, tag = "5")]
    pub columns: Vec<SourceColumnLayout>,
}

#[derive(Clone, PartialEq, Eq, prost::Message)]
pub struct SourceColumnLayout {
    /// Original PostgreSQL attribute number. Dropped columns can leave gaps.
    #[prost(int32, tag = "1")]
    pub number: i32,
    #[prost(bytes = "vec", tag = "2")]
    pub name: Vec<u8>,
    #[prost(bytes = "vec", tag = "3")]
    pub formatted_type: Vec<u8>,
    #[prost(bool, tag = "4")]
    pub not_null: bool,
    /// The PostgreSQL attidentity byte, or zero.
    #[prost(uint32, tag = "5")]
    pub identity: u32,
    /// The PostgreSQL attgenerated byte, or zero.
    #[prost(uint32, tag = "6")]
    pub generated: u32,
    /// A column-level collation override captured by pg_dump, or zero.
    #[prost(uint32, tag = "7")]
    pub collation_oid: u32,
    /// A default or generation expression collected by pg_dump.
    #[prost(bytes = "vec", optional, tag = "8")]
    pub expression: Option<Vec<u8>>,
}

#[repr(C)]
struct ColumnLayoutView {
    name: *const c_char,
    formatted_type: *const c_char,
    expression: *const c_char,
    number: c_int,
    collation_oid: u32,
    identity: c_char,
    generated: c_char,
    not_null: bool,
}

#[repr(C)]
pub(crate) struct TableLayoutView {
    schema: *const c_char,
    name: *const c_char,
    columns: *const ColumnLayoutView,
    column_count: usize,
    relation_oid: u32,
    relation_kind: c_char,
}

pub(crate) unsafe extern "C" fn receive(context: *mut c_void, layout: *const TableLayoutView) {
    // The adapter owns these pointers for the duration of this call.
    let archive = unsafe { &mut *context.cast::<Archive>() };
    let layout = unsafe { &*layout };
    let columns = if layout.column_count == 0 {
        &[]
    } else {
        unsafe { std::slice::from_raw_parts(layout.columns, layout.column_count) }
    };
    let copy = |ptr| unsafe { CStr::from_ptr(ptr) }.to_bytes().to_vec();
    archive.table_layouts.push(SourceTableLayout {
        relation_oid: layout.relation_oid,
        schema: copy(layout.schema),
        name: copy(layout.name),
        relation_kind: u32::from(layout.relation_kind as u8),
        columns: columns
            .iter()
            .map(|column| SourceColumnLayout {
                number: column.number,
                name: copy(column.name),
                formatted_type: copy(column.formatted_type),
                not_null: column.not_null,
                identity: u32::from(column.identity as u8),
                generated: u32::from(column.generated as u8),
                collation_oid: column.collation_oid,
                expression: (!column.expression.is_null()).then(|| copy(column.expression)),
            })
            .collect(),
    });
}
